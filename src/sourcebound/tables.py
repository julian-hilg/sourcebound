"""Table bodies in the house style (booktabs, no vertical rules, numbers right-aligned).

The generated file holds only the tabular; caption, label and note stay in the
deliverable, so the same table can be reused in paper, note and slides:

    \\begin{table}[t]
      \\caption{Summary statistics}\\label{tab:summary}
      \\input{generated/tables/summary.tex}   % copied there by `sb sync`
      \\tablenote{Daily data, 1999--2026. Source: ECB.}
    \\end{table}

    from sourcebound import tables
    tables.from_rows(path, header=["", "Mean", "SD"], rows=[["EUR/USD", 1.17, 0.16]], decimals=3)
    tables.from_polars(df, path, decimals={"mean": 3})
    tables.regression(path, models={"(1)": {"coef": {"beta": (0.52, 0.04)}, "stats": {"N": 6512}}})
A CSV twin is written next to every table (machine-readable, publishable).
"""
from __future__ import annotations

import csv
import re
import math
from pathlib import Path

import polars as pl

from . import config


def _german() -> bool:
    p = config.project(required=False)
    return bool(p and p.german)


def num(x, decimals: int = 2, *, german: bool | None = None, thousands: bool = True) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return ""
    if isinstance(x, str):
        return x
    german = _german() if german is None else german
    s = f"{x:,.{decimals}f}" if thousands else f"{x:.{decimals}f}"
    if german:
        s = s.replace(",", "\0").replace(".", "{,}").replace("\0", ".")
    else:
        s = s.replace(",", "{,}")
    return s.replace("-", "$-$")


def _esc(s: str) -> str:
    return (str(s).replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#"))


def _write(path: Path, header: list[str], body: list[list[str]], align: str,
           groups: list[tuple[str, int]] | None, midrules: set[int], raw_rows: list[list]) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    out = [f"% generated by sourcebound.tables -- edit the script, not this file",
           f"\\begin{{tabular}}{{@{{}}{align}@{{}}}}", "\\toprule"]
    if groups:
        cells, rules, col = [], [], 1
        for label, span in groups:
            cells.append(f"\\multicolumn{{{span}}}{{c}}{{{label}}}" if span > 1 else label)
            if label:
                rules.append(f"\\cmidrule(lr){{{col}-{col + span - 1}}}")
            col += span
        out += [" & ".join(cells) + " \\\\", "".join(rules)]
    out += [" & ".join(header) + " \\\\", "\\midrule"]
    for i, row in enumerate(body):
        if i in midrules:
            out.append("\\midrule")
        out.append(" & ".join(row) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    with path.with_suffix(".csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow([h.replace("\\", "").replace("$", "") for h in header])
        w.writerows(raw_rows)
    return path


def displayed(tex: Path) -> tuple[list[str], list[list[str]]] | None:
    """(header, rows) of a generated table as it is printed: the formatted cells, not the raw values.

    The CSV twin holds the exact numbers; a renderer of another format wants what the PDF shows.
    """
    if not Path(tex).exists():
        return None
    rows = []
    for ln in Path(tex).read_text(encoding="utf-8").splitlines():
        ln = ln.strip()
        if not ln.endswith("\\\\") or "\\multicolumn" in ln:
            continue
        cells = [c.strip().replace("{,}", ",").replace("$-$", "\u2212") for c in re.split(r"(?<!\\)&", ln[:-2])]
        rows.append(cells)
    return (rows[0], rows[1:]) if rows else None


def from_rows(path, *, header: list[str], rows: list[list], decimals: int | list[int] = 2,
              align: str | None = None, groups: list[tuple[str, int]] | None = None,
              midrules: set[int] | None = None) -> Path:
    """Generic table: first column text (left), other columns numbers (right)."""
    ncol = len(header)
    decs = decimals if isinstance(decimals, list) else [decimals] * ncol
    body = [[_esc(r[0])] + [num(v, decs[j + 1]) if not isinstance(v, str) else _esc(v)
                            for j, v in enumerate(r[1:])] for r in rows]
    return _write(path, [_esc(h) for h in header], body, align or "l" + "r" * (ncol - 1),
                  groups, midrules or set(), rows)


def from_polars(df: pl.DataFrame, path, *, decimals: dict[str, int] | int = 2,
                labels: dict[str, str] | None = None, **kw) -> Path:
    labels = labels or {}
    header = [labels.get(c, c) for c in df.columns]
    dec = [decimals.get(c, 2) if isinstance(decimals, dict) else decimals for c in df.columns]
    return from_rows(path, header=header, rows=[list(r) for r in df.iter_rows()], decimals=dec, **kw)


def regression(path, *, models: dict[str, dict], order: list[str] | None = None,
               labels: dict[str, str] | None = None, stats: list[tuple[str, str, int]] | None = None,
               decimals: int = 3, stars: bool = False) -> Path:
    """Coefficients with standard errors in parentheses below.

    models = {"(1)": {"coef": {"x": (b, se) or (b, se, p)}, "stats": {"N": 100, "R2": 0.31}}}
    stats  = [("N", "Observations", 0), ("R2", "$R^2$", 2)]
    """
    labels = labels or {}
    names = list(models)
    order = order or list(dict.fromkeys(k for m in models.values() for k in m["coef"]))
    stats = stats or [("N", "Observations", 0)]

    def star(p):
        if not stars or p is None:
            return ""
        return "^{***}" if p < 0.01 else "^{**}" if p < 0.05 else "^{*}" if p < 0.1 else ""

    body, raw = [], []
    for k in order:
        brow, srow, rrow = [_esc(labels.get(k, k))], [""], [k]
        for n in names:
            c = models[n]["coef"].get(k)
            if c is None:
                brow.append(""); srow.append(""); rrow.append("")
                continue
            b, se, p = (*c, None)[:3]
            brow.append(f"${num(b, decimals).replace('$', '')}{star(p)}$")
            srow.append(f"({num(se, decimals)})")
            rrow.append(f"{b} ({se})")
        body += [brow, srow]
        raw.append(rrow)
    mid = {len(body)}
    for key, lab, d in stats:
        body.append([lab] + [num(models[n].get("stats", {}).get(key), d) for n in names])
        raw.append([key] + [models[n].get("stats", {}).get(key) for n in names])
    return _write(path, [""] + names, body, "l" + "c" * len(names), None, mid, raw)
